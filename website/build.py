def build_flipbook(env_base: dict[str, str]) -> dict:
    binary = flip_bin()
    with tempfile.TemporaryDirectory(prefix="flip-site-") as tmp:
        workspace = Path(tmp)
        home = workspace / "flip-home"
        home.mkdir()
        env = {
            **env_base,
            "FLIP_HOME": str(home),          # never touch the operator's ~/.flip
            "FLIP_ACTOR": "agent:harness",  # deterministic attribution
            "NO_COLOR": "1",
            "COLUMNS": "88",
        }
        for name, body in DEMO_FILES.items():
            (workspace / name).write_text(body, encoding="utf-8")

        notebook = workspace / DEMO_SLUG
        steps: list[dict] = []
        previous: dict[str, float] = {}

        for index, plan in enumerate(step_plan(), start=1):
            cwd = workspace if plan.get("cwd") == "root" else notebook
            for rel in plan.get("ensure_dirs", []):
                (notebook / rel).mkdir(parents=True, exist_ok=True)
            outputs: list[str] = []
            code = 0
            for argv in plan["commands"]:
                proc = run([binary, *argv], cwd=cwd, env=env)
                chunk = (proc.stdout or "") + (proc.stderr or "")
                outputs.append(chunk.rstrip("\n"))
                code = proc.returncode
                if code != 0 and not (plan.get("expect_failure") or plan.get("allow_failure")):
                    raise BuildError(
                        f"step {plan['id']}: `flip {' '.join(argv)}` exited {code}\n{chunk}"
                    )
            if plan.get("expect_failure") and code == 0:
                raise BuildError(
                    f"step {plan['id']} expected a refusal but the command succeeded — "
                    "the verification bar may have been weakened"
                )

            current = snapshot_tree(notebook)
            tree = []
            for path in sorted(current):
                if path not in previous:
                    state = "added"
                elif current[path] != previous[path]:
                    state = "changed"
                else:
                    state = "same"
                tree.append({"path": path, "state": state})
            previous = current

            record = dict(plan["record"])
            spec = record.pop("kind")
            if spec == "stdout":
                body = "\n\n".join(chunk for chunk in outputs if chunk) or "(no output)"
                limit = record.pop("truncate", 0)
                if limit:
                    lines = body.splitlines()
                    if len(lines) > limit:
                        body = "\n".join(lines[:limit])
                        record["truncated"] = True
                record["text"] = body
                record["path"] = "stdout"
            else:
                if spec == "glob":
                    # index.md in each directory is a generated listing, never an
                    # entity page — and the entity we mean is the one this step
                    # just touched, so select by mtime rather than by name.
                    matches = [
                        path
                        for path in notebook.glob(record.pop("pattern"))
                        if path.name != "index.md"
                    ]
                    if not matches:
                        raise BuildError(f"step {plan['id']}: record glob matched nothing")
                    target = max(matches, key=lambda p: p.stat().st_mtime_ns)
                else:
                    target = notebook / record["path"]
                if not target.exists():
                    raise BuildError(f"step {plan['id']}: record path {target} is missing")
                if spec == "jsonl":
                    lines = [
                        line
                        for line in target.read_text(encoding="utf-8").splitlines()
                        if line.strip()
                    ]
                    record["text"] = json.dumps(json.loads(lines[-1]), indent=2)
                else:
                    text, truncated = read_slice(target)
                    record["text"] = text
                    if truncated:
                        record["truncated"] = True
                record["path"] = target.relative_to(notebook).as_posix()

            steps.append(
                {
                    "n": index,
                    "id": plan["id"],
                    "say": plan.get("say", ""),
                    "reply": plan.get("reply", ""),
                    "act": plan["act"],
                    "title": plan["title"],
                    "narrative": plan["narrative"],
                    "spec": plan["spec"],
                    # Shell-quoted: the site shows a copy button beside these, so
                    # what is displayed has to be what you can actually paste.
                    "commands": ["flip " + shlex.join(argv) for argv in plan["commands"]],
                    "command_outputs": [
                        {
                            "command": "flip " + shlex.join(argv),
                            "stdout": output,
                        }
                        for argv, output in zip(plan["commands"], outputs, strict=True)
                    ],
                    "stdout": "\n\n".join(chunk for chunk in outputs if chunk),
                    "exit_code": code,
                    "refused": bool(plan.get("expect_failure")),
                    "tree": tree,
                    "record": record,
                }
            )

        # Cross-check the spec map against what the implementation really wrote.
        frontmatter = harvest_frontmatter(notebook)

        # The flip-render/2 projection of this same scratch notebook, taken
        # before the temp directory goes away — the canonical data source
        # for site/notebook.html.
        export = export_demo_notebook(binary, notebook, env)

    return {"steps": steps, "frontmatter_seen": frontmatter, "export": export}


def export_demo_notebook(binary: str, notebook: Path, env: dict[str, str]) -> dict:
    """Run the real `flip export json --render-version 2` against the scratch
    demo notebook while it still exists on disk, and return the parsed
    flip-render/2 projection.

    This is the canonical data source for notebook.html: every source,
    claim, question, decision, session, and log line on that page comes from
    this one call, not from anything hand-authored. Fails loud if the export
    itself fails, or if it does not carry the contract this site's notebook
    viewer was built against.

    Before exporting, the demo's WORK gets written the way an agent would
    write it — a findings page in analysis/ — because a notebook is the
    completed/in-progress work AND its dependent sources, and the viewer
    should show both.
    """
    analysis = notebook / "analysis"
    analysis.mkdir(exist_ok=True)
    (analysis / "findings.md").write_text(
        "---\n"
        "type: Finding\n"
        "title: Where OKF came from and where it may go\n"
        "---\n\n"
        "# Bottom line\n\n"
        "OKF's declared direct precedent is LLM-wiki [C1-C2], but its public\n"
        "GoogleCloudPlatform history begins at a snapshot import that omitted\n"
        "the upstream Git history [C3-C4]. The current pressure points cluster\n"
        "around stable identity, agent routing, relationship semantics,\n"
        "large-bundle retrieval, and cross-bundle composition [C5-C6].\n\n"
        "No formal roadmap appeared on the three checked file and milestone\n"
        "surfaces [C7]. Planning is still visible through named deferred work\n"
        "and active proposals [C8]: direction of travel, not a public schedule.\n",
        encoding="utf-8",
    )
    proc = run(
        [binary, "export", "json", "--render-version", "2", "--include-private", "--out", "-"],
        cwd=notebook,
        env=env,
    )
    if proc.returncode != 0:
        raise BuildError(
            f"`flip export json --render-version 2` exited {proc.returncode}:\n"
            f"{(proc.stdout or '') + (proc.stderr or '')}"
        )
    try:
        payload = json.loads(proc.stdout)
    except json.JSONDecodeError as exc:
        raise BuildError(
            f"`flip export json --render-version 2` did not emit valid JSON: {exc}"
        ) from exc
    if payload.get("contract") != "flip-render/2":
        raise BuildError(
            "expected the flip-render/2 contract from `flip export json "
            f"--render-version 2`, got {payload.get('contract')!r}"
        )
    return payload


def harvest_frontmatter(notebook: Path) -> dict[str, list[str]]:
    """Collect the frontmatter keys each entity type actually carries."""
    seen: dict[str, set[str]] = {}
    for path in notebook.rglob("*.md"):
        text = path.read_text(encoding="utf-8", errors="replace")
        if not text.startswith("---\n"):
            continue
        end = text.find("\n---", 4)
        if end == -1:
            continue
        block = text[4:end]
        keys = re.findall(r"^([A-Za-z_][A-Za-z0-9_]*):", block, re.M)
        kind = "Manifest"
        for line in block.splitlines():
            if line.startswith("type:"):
                kind = line.split(":", 1)[1].strip().strip("\"'")
                break
        seen.setdefault(kind, set()).update(keys)
    return {kind: sorted(keys) for kind, keys in sorted(seen.items())}


