#!/usr/bin/env python3
"""Generate the flip site's data from the repository and the real CLI.

The flipbook replays a compact, offline-safe version of a completed public
reporting run against a scratch notebook. Every command, output, record, and
tree change is generated by ``flip``; the conversational framing is distilled
from the run whose complete notebook lives in ``flip-examples/okf-origins``.
The spec map comes from parsing SPEC.md and cross-checking it against the
generated notebook; coordinates come from ``pyproject.toml``, the tests, and
git.

Every derivation is fail-loud: a drifted spec section, a frontmatter key the
implementation no longer writes, or a CLI command that vanished raises and the
site does not build. That is the point — the site cannot quietly describe a
flip that no longer exists.

Stdlib only, and no network access. Run via ``artoo build``.
"""

