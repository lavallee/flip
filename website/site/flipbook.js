/* The flipbook: one scrolling conversation between a person and their agent,
   generated by running the real CLI at build time.

   Every step renders as an exchange: the human's message (when there was one),
   the agent's conversational reply, the command(s) it ran as a one-line
   monospace summary, and a closed-by-default <details> holding the full
   under-the-hood record — narrative, commands with output, the file that was
   written, and the notebook tree. Act changes become small section kickers.
   Each exchange is anchored (#step-grade …) so a moment stays linkable; old
   per-frame hashes (#grade) redirect to the same anchor. */
(function () {
  "use strict";

  var book = window.__FLIP_BOOK__;
  var spec = window.__FLIP_SPEC__;
  var kit = window.flipsite;
  var chat = document.getElementById("fb-chat");
  if (!book || !book.steps || !book.steps.length || !kit || !chat) return;

  var steps = book.steps;

  function el(tag, cls, text) {
    var node = document.createElement(tag);
    if (cls) node.className = cls;
    if (text != null) node.textContent = text;
    return node;
  }

  // -- the file tree --------------------------------------------------------
  // Rendered as a real nested list from the flat path list, so screen readers
  // get the hierarchy and the indentation is not decorative whitespace.
  function renderTree(entries) {
    var root = { dirs: {}, files: [] };
    entries.forEach(function (entry) {
      var parts = entry.path.split("/");
      var node = root;
      for (var i = 0; i < parts.length - 1; i += 1) {
        node.dirs[parts[i]] = node.dirs[parts[i]] || { dirs: {}, files: [] };
        node = node.dirs[parts[i]];
      }
      node.files.push({ name: parts[parts.length - 1], state: entry.state });
    });

    function build(node) {
      var list = document.createElement("ul");
      Object.keys(node.dirs).sort().forEach(function (name) {
        var item = document.createElement("li");
        var label = el("span", "dir", "▸ " + name + "/");
        item.appendChild(label);
        item.appendChild(build(node.dirs[name]));
        list.appendChild(item);
      });
      node.files.sort(function (a, b) { return a.name.localeCompare(b.name); })
        .forEach(function (file) {
          var item = document.createElement("li");
          item.className = "file"
            + (file.state === "added" ? " is-added" : "")
            + (file.state === "changed" ? " is-changed" : "");
          var mark = el("span", "mark", file.state === "added" ? "+" : (file.state === "changed" ? "~" : ""));
          mark.setAttribute("aria-hidden", "true");
          item.appendChild(mark);
          item.appendChild(document.createTextNode(file.name));
          if (file.state !== "same") {
            var sr = el("span", "visually-hidden",
              file.state === "added" ? " (added this step)" : " (changed this step)");
            item.appendChild(sr);
          }
          list.appendChild(item);
        });
      return list;
    }

    var wrap = el("div", "tree");
    wrap.appendChild(build(root));
    return wrap;
  }

  // -- the under-the-hood detail (closed by default) ------------------------
  function renderDetails(step) {
    var details = el("details", "fb__details");
    var summary = el("summary", null, "Under the hood — " + step.title);
    details.appendChild(summary);

    var body = el("div", "fb__details-body");

    var narrative = el("p", "fb__narrative");
    narrative.appendChild(kit.codeify(step.narrative));
    body.appendChild(narrative);

    body.appendChild(el("p", "pane-label", "What the agent ran"));
    step.commands.forEach(function (command) {
      var line = el("div", "cmd");
      var code = document.createElement("code");
      code.textContent = command;
      line.appendChild(code);
      body.appendChild(line);
    });
    // The record pane already carries stdout when the record *is* the output;
    // only show a separate output block when they differ.
    if (step.stdout && step.record.path !== "stdout") {
      body.appendChild(kit.record({
        path: "output",
        refused: step.refused,
        text: step.stdout,
        caption: step.refused ? "This command exits " + step.exit_code + "." : null
      }));
    }

    body.appendChild(el("p", "pane-label", "What was recorded"));
    body.appendChild(kit.record({
      path: step.record.path,
      refused: step.refused,
      truncated: step.record.truncated,
      text: step.record.text,
      caption: step.record.caption
    }));

    if (step.tree && step.tree.length) {
      var added = step.tree.filter(function (t) { return t.state === "added"; }).length;
      var changed = step.tree.filter(function (t) { return t.state === "changed"; }).length;
      var legend = added || changed
        ? " · " + added + " added, " + changed + " changed"
        : " · unchanged";
      body.appendChild(el("p", "pane-label", "The notebook on disk" + legend));
      body.appendChild(renderTree(step.tree));
    }

    var specLink = el("a", "spec-link", kit.specLabel(step.spec, spec && spec.sections));
    specLink.href = kit.specHref(step.spec, spec && spec.sections);
    var specRow = el("p", "fb__spec-row");
    specRow.appendChild(specLink);
    body.appendChild(specRow);

    details.appendChild(body);
    return details;
  }

  // -- one exchange ---------------------------------------------------------
  function renderExchange(step) {
    var exchange = el("article", "fb__exchange");
    exchange.id = "step-" + step.id;

    if (step.say) {
      var say = el("div", "fb__say");
      var bubble = el("div", "bubble");
      bubble.appendChild(el("b", null, "You"));
      bubble.appendChild(document.createTextNode(step.say));
      say.appendChild(bubble);
      exchange.appendChild(say);
    } else {
      exchange.appendChild(el("p", "fb__unprompted",
        "unprompted — the notebook's discipline has the agent do this"));
    }

    var agent = el("div", "fb__agent");
    var reply = el("div", "bubble");
    reply.appendChild(el("b", null, "Agent"));
    reply.appendChild(document.createTextNode(step.reply || ""));

    // The default level of under-the-hood detail: the command(s) run, and the
    // exit code when the CLI refused. Everything else lives in <details>.
    var ran = el("div", "fb__ran");
    step.commands.forEach(function (command) {
      ran.appendChild(el("code", "fb__ran-line", "$ " + command));
    });
    if (step.refused) {
      ran.appendChild(el("span", "fb__exit", "exit " + step.exit_code));
    }
    reply.appendChild(ran);
    agent.appendChild(reply);

    agent.appendChild(renderDetails(step));
    exchange.appendChild(agent);
    return exchange;
  }

  // -- the whole conversation, with act kickers at act boundaries -----------
  var currentAct = null;
  steps.forEach(function (step) {
    if (step.act !== currentAct) {
      currentAct = step.act;
      chat.appendChild(el("h2", "fb__act-kicker", step.act));
    }
    chat.appendChild(renderExchange(step));
  });

  if (kit.enhance) kit.enhance();

  if (document.getElementById("fb-vintage") && book.generated) {
    var stamp = document.createElement("span");
    stamp.textContent = " Generated " + book.generated.replace("T", " ").replace("+00:00", " UTC") + ".";
    document.getElementById("fb-vintage").appendChild(stamp);
  }

  // Old links used bare step ids (#grade); forward them to the new anchors.
  var hash = (window.location.hash || "").replace(/^#/, "");
  if (hash && !document.getElementById(hash)) {
    var target = document.getElementById("step-" + hash);
    if (target) window.location.replace("#step-" + hash);
  }
})();
